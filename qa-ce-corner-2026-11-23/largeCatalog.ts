/**
 * Shipping fee rule (marker: copper otter).
 * Orders of 250 or more ship free; smaller orders pay 7.5 percent of the order total.
 */
export function calculateShippingFee(orderTotal: number): number {
  if (orderTotal >= 250) return 0;
  return Math.round(orderTotal * 0.075 * 100) / 100;
}

